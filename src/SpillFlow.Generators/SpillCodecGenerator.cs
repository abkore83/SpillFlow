using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SpillFlow.Generators;

[Generator]
public sealed class SpillCodecGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor UnsupportedProperty = new(
        "SPILL001", "Unsupported codec property",
        "Property '{0}' has unsupported type '{1}'", "SpillFlow", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidModel = new(
        "SPILL002", "Invalid codec model",
        "Type '{0}' cannot generate a safe spill codec: {1}", "SpillFlow", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidProperty = new(
        "SPILL003", "Invalid codec property",
        "Property '{0}' must be a non-indexed public instance property with public get and set accessors",
        "SpillFlow", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName(
            "SpillFlow.GenerateSpillCodecAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol);
        context.RegisterSourceOutput(types, Generate);
    }

    private static void Generate(SourceProductionContext context, INamedTypeSymbol type)
    {
        if (type.IsGenericType || type.IsAbstract ||
            type.TypeKind == TypeKind.Class &&
            (type.BaseType is { SpecialType: not SpecialType.System_Object } ||
             !type.InstanceConstructors.Any(ctor =>
                 ctor.Parameters.Length == 0 && ctor.DeclaredAccessibility == Accessibility.Public)))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidModel, type.Locations.FirstOrDefault(), type.Name,
                "use a non-generic, non-abstract type without a custom base class and with a public parameterless constructor"));
            return;
        }

        var publicProperties = type.GetMembers().OfType<IPropertySymbol>()
            .Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public).ToImmutableArray();
        foreach (var property in publicProperties)
        {
            if (property.IsIndexer || property.GetMethod?.DeclaredAccessibility != Accessibility.Public ||
                property.SetMethod?.DeclaredAccessibility != Accessibility.Public)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidProperty, property.Locations.FirstOrDefault(), property.Name));
                return;
            }
        }

        var properties = publicProperties
            .OrderBy(p => p.Name, StringComparer.Ordinal)
            .ToImmutableArray();

        foreach (var property in properties)
        {
            if (!IsSupported(property.Type))
            {
                context.ReportDiagnostic(Diagnostic.Create(UnsupportedProperty, property.Locations.FirstOrDefault(),
                    property.Name, property.Type.ToDisplayString()));
                return;
            }
        }

        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        var model = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var codec = type.Name + "SpillCodec";
        var accessibility = type.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        var size = string.Join(" + ", properties.Select(SizeExpression).DefaultIfEmpty("0"));
        var write = string.Join("\n", properties.Select(WriteStatement));
        var read = string.Join("\n", properties.Select(ReadStatement));
        var assignments = string.Join(",\n", properties.Select(p => $"            {Escape(p.Name)} = {Local(p)}"));

        var source = $$"""
// <auto-generated />
#nullable enable
using System;
using System.Buffers.Binary;
using System.IO;
using System.Text;
{{(ns is null ? "" : $"namespace {ns};")}}

{{accessibility}} sealed class {{codec}} : global::SpillFlow.ISpillCodec<{{model}}>
{
    public int GetEncodedSize({{model}} value) => checked({{size}});

    public byte[] Encode({{model}} value)
    {
        var bytes = new byte[GetEncodedSize(value)];
        var offset = 0;
{{write}}
        return bytes;
    }

    public {{model}} Decode(ReadOnlySpan<byte> bytes)
    {
        var offset = 0;
{{read}}
        if (offset != bytes.Length) throw new InvalidDataException("Unexpected trailing codec data.");
        return new {{model}}
        {
{{assignments}}
        };
    }

    private static ReadOnlySpan<byte> Take(ReadOnlySpan<byte> bytes, ref int offset, int length)
    {
        if (length < 0 || length > bytes.Length - offset) throw new InvalidDataException("Invalid codec field length.");
        var result = bytes.Slice(offset, length);
        offset += length;
        return result;
    }
}
""";
        context.AddSource(codec + ".g.cs", SourceText.From(source, Encoding.UTF8));
    }

    private static bool IsSupported(ITypeSymbol type) => type.SpecialType is
        SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Boolean or SpecialType.System_String
        || type.ToDisplayString() == "System.Guid";

    private static string Local(IPropertySymbol p) => "value_" + p.Name;
    private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
    private static string SizeExpression(IPropertySymbol p) => p.Type.SpecialType switch
    {
        SpecialType.System_Int32 => "4",
        SpecialType.System_Int64 => "8",
        SpecialType.System_Boolean => "1",
        SpecialType.System_String when p.NullableAnnotation == NullableAnnotation.Annotated =>
            $"4 + (value.{Escape(p.Name)} is null ? 0 : Encoding.UTF8.GetByteCount(value.{Escape(p.Name)}))",
        SpecialType.System_String =>
            $"4 + Encoding.UTF8.GetByteCount(value.{Escape(p.Name)} ?? throw new InvalidDataException(\"Property '{p.Name}' cannot be null.\"))",
        _ => "16"
    };

    private static string WriteStatement(IPropertySymbol p)
    {
        var n = p.Name;
        var access = Escape(n);
        return p.Type.SpecialType switch
        {
            SpecialType.System_Int32 => $"        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(offset, 4), value.{access}); offset += 4;",
            SpecialType.System_Int64 => $"        BinaryPrimitives.WriteInt64LittleEndian(bytes.AsSpan(offset, 8), value.{access}); offset += 8;",
            SpecialType.System_Boolean => $"        bytes[offset++] = value.{access} ? (byte)1 : (byte)0;",
            SpecialType.System_String when p.NullableAnnotation == NullableAnnotation.Annotated =>
                $"        if (value.{access} is null) {{ BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(offset, 4), -1); offset += 4; }} else {{ var length_{n} = Encoding.UTF8.GetBytes(value.{access}, bytes.AsSpan(offset + 4)); BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(offset, 4), length_{n}); offset += 4 + length_{n}; }}",
            SpecialType.System_String =>
                $"        var text_{n} = value.{access} ?? throw new InvalidDataException(\"Property '{n}' cannot be null.\"); var length_{n} = Encoding.UTF8.GetBytes(text_{n}, bytes.AsSpan(offset + 4)); BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(offset, 4), length_{n}); offset += 4 + length_{n};",
            _ => $"        if (!value.{access}.TryWriteBytes(bytes.AsSpan(offset, 16))) throw new InvalidOperationException(); offset += 16;"
        };
    }

    private static string ReadStatement(IPropertySymbol p)
    {
        var local = Local(p);
        return p.Type.SpecialType switch
        {
            SpecialType.System_Int32 => $"        var {local} = BinaryPrimitives.ReadInt32LittleEndian(Take(bytes, ref offset, 4));",
            SpecialType.System_Int64 => $"        var {local} = BinaryPrimitives.ReadInt64LittleEndian(Take(bytes, ref offset, 8));",
            SpecialType.System_Boolean => $"        var raw_{p.Name} = Take(bytes, ref offset, 1)[0]; if (raw_{p.Name} > 1) throw new InvalidDataException(\"Invalid Boolean value.\"); var {local} = raw_{p.Name} == 1;",
            SpecialType.System_String when p.NullableAnnotation == NullableAnnotation.Annotated =>
                $"        var length_{p.Name} = BinaryPrimitives.ReadInt32LittleEndian(Take(bytes, ref offset, 4)); if (length_{p.Name} < -1) throw new InvalidDataException(\"Invalid string length.\"); string? {local} = length_{p.Name} == -1 ? null : Encoding.UTF8.GetString(Take(bytes, ref offset, length_{p.Name}));",
            SpecialType.System_String =>
                $"        var length_{p.Name} = BinaryPrimitives.ReadInt32LittleEndian(Take(bytes, ref offset, 4)); var {local} = Encoding.UTF8.GetString(Take(bytes, ref offset, length_{p.Name}));",
            _ => $"        var {local} = new Guid(Take(bytes, ref offset, 16));"
        };
    }
}
